// infrastructure/SystemdRemoteController.ts — systemd --user lifecycle over SSH (task 4.5)
//
// Every mutation happens over the remotes RemoteCommandRunner port (type-only
// import per ADR-0015): unit file (FIXED template — no user input ever
// interpolated), daemon-reload, enable/disable, linger show/enable/disable,
// and KillUserProcesses detection (busctl → logind.conf fallback → unknown,
// warning-only per spec). Linger toggles record the by-tako flag through the
// injected meta seam (design D8 — the flag is recorded, never guessed).
//
// Threat matrix (systemd unit lifecycle): a pre-existing unit is overwritten
// ONLY when its ExecStart references %h/.tako/tako; a foreign unit is a hard
// refusal naming the path. Every systemctl step is exit-checked and failures
// surface stderr. Polkit linger denials surface an actionable error naming
// the polkit action and the sudo remedy.
import type { RemoteCommandResult, RemoteCommandRunner } from '../../remotes/application/RemoteCommandRunner.js';
import {
  parseKillUserProcessesConf,
  parseKillUserProcessesOutput,
  parseLingerShowUserOutput,
} from '../application/use-cases/InstallAgent.js';

export const AGENT_UNIT_NAME = 'tako-agent.service';
/** Fixed unit template (design §Probe Mechanics): nothing here is dynamic. */
export const AGENT_UNIT_TEMPLATE = `# Managed by Tako — regenerated by "tako agent install". Do not edit.
[Unit]
Description=Tako homelab agent

[Service]
ExecStart=%h/.tako/tako agent run
Restart=on-failure
RestartSec=3
Environment=TAKO_AGENT=1

[Install]
WantedBy=default.target
`;

/** Seam over agent_meta for the by-tako linger flag (satisfied by persistence/agent-meta). */
export interface LingerMetaStore {
  getLingerEnabledByTako(): boolean | undefined;
  setLingerEnabledByTako(value: boolean): void;
}

/** Thrown when a pre-existing unit file does not belong to Tako. */
export class ForeignUnitFileError extends Error {
  constructor(path: string) {
    super(
      `refusing to overwrite ${path}: its ExecStart does not reference %h/.tako/tako, so the unit was not installed by Tako — inspect it and remove it manually if it is stale`
    );
    this.name = 'ForeignUnitFileError';
  }
}

/** Thrown when polkit denies linger management — carries the remedy (3.14). */
export class PolkitLingerDeniedError extends Error {
  constructor(stderr: string) {
    super(
      `polkit denied the linger operation (org.freedesktop.login1.set-self-linger): ${stderr.trim() || 'not authorized'} — remedy: run "sudo loginctl enable-linger $USER" on the server once, then retry the install`
    );
    this.name = 'PolkitLingerDeniedError';
  }
}

export interface SystemdRemoteControllerOptions {
  readonly runner: RemoteCommandRunner;
  /** Absent on read-only paths (e.g. status) — linger toggles then skip recording. */
  readonly meta?: LingerMetaStore;
}

export class SystemdRemoteController {
  readonly #runner: RemoteCommandRunner;
  readonly #meta?: LingerMetaStore;
  #home?: string;

  constructor(options: SystemdRemoteControllerOptions) {
    this.#runner = options.runner;
    this.#meta = options.meta;
  }

  /**
   * Resolve the remote home ONCE and build ABSOLUTE paths from it: `$HOME`
   * must never reach a shell command inside single quotes (it would stay
   * literal and the unit would land outside systemd's search path).
   */
  async #unitFilePath(): Promise<string> {
    if (this.#home === undefined) {
      const probe = await this.#run('printf %s "$HOME"');
      const home = probe.stdout.trim();
      if (probe.exitCode !== 0 || home.length === 0) {
        throw new Error(`cannot resolve the remote home directory — refusing to place the unit file blindly`);
      }
      this.#home = home;
    }
    return `${this.#home}/.config/systemd/user/${AGENT_UNIT_NAME}`;
  }

  /**
   * Write the fixed unit template. A pre-existing unit is inspected first:
   * overwritten only when its ExecStart references %h/.tako/tako (it is
   * ours), refused otherwise (foreign unit — threat matrix row 3).
   */
  async writeUnitFile(): Promise<void> {
    const unitPath = await this.#unitFilePath();
    const existing = await this.#run(`cat '${unitPath}' 2>/dev/null || true`);
    if (existing.stdout.trim().length > 0 && !isTakoUnit(existing.stdout)) {
      throw new ForeignUnitFileError(unitPath);
    }
    const unitDir = unitPath.slice(0, unitPath.lastIndexOf('/'));
    await this.#run(
      `mkdir -p '${unitDir}' && cat > '${unitPath}' <<'TAKO_UNIT_EOF'\n${AGENT_UNIT_TEMPLATE}TAKO_UNIT_EOF`
    );
  }

  async daemonReload(): Promise<void> {
    await this.#run('systemctl --user daemon-reload');
  }

  async enableUnit(): Promise<void> {
    await this.#run(`systemctl --user enable --now ${AGENT_UNIT_NAME}`);
  }

  /**
   * 9.13: restart the unit ONLY when it is already active (`try-restart`
   * no-ops otherwise). `enable --now` cannot revive a stale ACTIVE unit
   * serving a deleted socket path — the reinstall must restart it to pick up
   * the fresh binary and re-create the socket listener.
   */
  async tryRestartUnit(): Promise<void> {
    await this.#run(`systemctl --user try-restart ${AGENT_UNIT_NAME}`);
  }

  /** Enable WITHOUT starting — pairs with try-restart to preserve boot-start
   * for a unit that was running but manually started (not enabled). */
  async enableUnitForBoot(): Promise<void> {
    await this.#run(`systemctl --user enable ${AGENT_UNIT_NAME}`);
  }

  async disableUnit(): Promise<void> {
    await this.#run(`systemctl --user disable --now ${AGENT_UNIT_NAME}`);
  }

  async removeUnitFile(): Promise<void> {
    const unitPath = await this.#unitFilePath();
    await this.#run(`rm -f '${unitPath}'`);
  }

  /** `loginctl show-user` parse → true/false; unreadable → 'unknown'. */
  async showLinger(): Promise<boolean | 'unknown'> {
    const result = await this.#run('loginctl show-user "$USER" --property=Linger');
    if (result.exitCode !== 0) return 'unknown';
    return parseLingerShowUserOutput(result.stdout) ?? 'unknown';
  }

  /** Enable linger and record by-tako=true; polkit denial → actionable error. */
  async enableLinger(): Promise<void> {
    const result = await this.#runner.run('loginctl enable-linger');
    if (result.exitCode !== 0) {
      throw new PolkitLingerDeniedError(result.stderr);
    }
    this.#meta?.setLingerEnabledByTako(true);
  }

  /** Disable linger and record by-tako=false (only ever called when by-tako). */
  async disableLinger(): Promise<void> {
    const result = await this.#runner.run('loginctl disable-linger');
    if (result.exitCode !== 0) {
      throw new PolkitLingerDeniedError(result.stderr);
    }
    this.#meta?.setLingerEnabledByTako(false);
  }

  /**
   * KillUserProcesses detection: busctl first, /etc/systemd/logind.conf
   * fallback (uncommented values only), else 'unknown' — warning-only per
   * spec; the probe still executes.
   */
  async detectKillUserProcesses(): Promise<boolean | 'unknown'> {
    const busctl = await this.#tryRun(
      'busctl get-property org.freedesktop.login1 /org/freedesktop/login1 org.freedesktop.login1.Manager KillUserProcesses'
    );
    if (busctl !== undefined && busctl.exitCode === 0) {
      const parsed = parseKillUserProcessesOutput(busctl.stdout);
      if (parsed !== undefined) return parsed;
    }
    const conf = await this.#tryRun('cat /etc/systemd/logind.conf');
    if (conf !== undefined && conf.exitCode === 0) {
      const parsed = parseKillUserProcessesConf(conf.stdout);
      if (parsed !== undefined) return parsed;
    }
    return 'unknown';
  }

  async #run(command: string): Promise<RemoteCommandResult> {
    const result = await this.#runner.run(command);
    if (result.exitCode !== 0 && isMutationCommand(command)) {
      const stderr = result.stderr.trim();
      const remedy = command.includes('systemctl') ? systemctlRemedy() : '';
      throw new Error(`remote command failed (exit ${result.exitCode ?? 'signal'}): ${command}\n${stderr}${remedy}`);
    }
    return result;
  }

  async #tryRun(command: string): Promise<RemoteCommandResult | undefined> {
    try {
      return await this.#runner.run(command);
    } catch {
      return undefined;
    }
  }
}

/** True when the unit content is Tako's (ExecStart references the agent binary). */
function isTakoUnit(content: string): boolean {
  return content.split('\n').some(line => line.startsWith('ExecStart=') && line.includes('%h/.tako/tako'));
}

/**
 * Threat-matrix remedy for generic systemctl step failures (one sentence):
 * point at the two diagnostic commands and the usual cause (vanished user
 * session), then retry.
 */
function systemctlRemedy(): string {
  return (
    ' — remedy: inspect the unit with "systemctl --user status tako-agent.service" and the logs with' +
    ' "journalctl --user -u tako-agent.service -n 50 --no-pager" (a vanished user session is the usual' +
    ' cause; "sudo loginctl enable-linger $USER" prevents it), then retry the command'
  );
}

/** Commands whose non-zero exit must throw (probes like `cat` inspect instead). */
function isMutationCommand(command: string): boolean {
  return (
    command.includes('systemctl') ||
    command.startsWith('mkdir -p') ||
    command.startsWith('loginctl enable-linger') ||
    command.startsWith('loginctl disable-linger')
  );
}
